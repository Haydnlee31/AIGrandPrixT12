"""Export the real FastAPI contract and dependency-free TypeScript wire types."""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.app.main import create_app


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(part) for part in schema[union])
    if "allOf" in schema:
        return " & ".join(ts_type(part) for part in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};" for name, value in schema.get("properties", {}).items()]
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            fields.append(f"[key: string]: {ts_type(additional)};")
        elif additional is True or not fields:
            fields.append("[key: string]: unknown;")
        return "{ " + " ".join(fields) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed outputs differ")
    args = parser.parse_args()
    contract = create_app(embedded_worker=False).openapi()
    types = ["// Generated by scripts/export_contracts.py from the API. Do not edit."]
    for name, schema in sorted(contract["components"]["schemas"].items()):
        types.append(f"export type {name} = {ts_type(schema)};")
    outputs = {
        ROOT / "contracts/openapi.json": json.dumps(contract, indent=2, sort_keys=True) + "\n",
        ROOT / "clients/javascript/types.d.ts": "\n".join(types) + "\n",
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"Wrote {path.relative_to(ROOT)}")
    if stale:
        sys.exit("Contract drift: " + ", ".join(stale) + ". Run make contracts.")
    if args.check:
        print("OpenAPI and TypeScript contracts match the API.")


if __name__ == "__main__":
    main()
