/** Real unpacked extension in an isolated Chromium profile; fixture provider only. */
import {mkdtemp, cp, readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath, pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const packageRoot = process.env.MYMAH_PLAYWRIGHT_ROOT;
if (!packageRoot) throw new Error('Set MYMAH_PLAYWRIGHT_ROOT to an installed Playwright package.');
const {chromium, expect} = await import(pathToFileURL(path.join(packageRoot, 'index.mjs')));
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const baseURL = process.env.MYMAH_TEST_API_URL || 'http://127.0.0.1:8768';
const token = process.env.MYMAH_TEST_ACCOUNT_TOKEN || 'browser-fixture-token';
const audio = process.env.MYMAH_TEST_VOICE_WAV;
if (!audio) throw new Error('Set MYMAH_TEST_VOICE_WAV to synthetic speech.');
if (!['127.0.0.1','localhost'].includes(new URL(baseURL).hostname)) throw new Error('Browser fixtures require an isolated loopback backend.');
const directory = await mkdtemp(path.join(tmpdir(), 'mymah-installed-extension-'));
const extension = path.join(directory,'extension');
await cp(root,extension,{recursive:true});
const manifest = JSON.parse(await readFile(path.join(extension,'manifest.json'),'utf8'));
// Pregrant only the isolated fixture host, so automation never approves access to real sites.
manifest.host_permissions = [`${new URL(baseURL).protocol}//${new URL(baseURL).hostname}/*`];
await writeFile(path.join(extension,'manifest.json'),JSON.stringify(manifest));
const context = await chromium.launchPersistentContext(path.join(directory,'profile'), {
  channel:'chromium', headless:true, viewport:{width:430,height:950},
  args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`,
    '--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream',`--use-file-for-fake-audio-capture=${audio}`]
});
const errors = [], checks = [];
let page;
try {
  let worker = context.serviceWorkers()[0];
  if (!worker) worker = await context.waitForEvent('serviceworker');
  const id = new URL(worker.url()).hostname;
  const actual = await worker.evaluate(() => chrome.runtime.getManifest());
  assert.equal(actual.version,'0.5.0'); assert.ok(actual.permissions.includes('sidePanel'));
  checks.push('manifest_and_service_worker_loaded');
  page = await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`chrome-extension://${id}/panel.html`);
  await page.locator('#profile-tab').click();
  await page.locator('#profile-connect').click();
  await page.locator('#backend-url').fill(baseURL);
  await page.locator('#settings-dialog details summary').click();
  if (!await page.locator('#backend-token').isVisible()) await page.locator('#settings-dialog details summary').click();
  await page.locator('#backend-token').fill(token);
  await page.locator('#connection-form button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#connection-label')?.textContent.includes('browser-fixture-user'));
  await page.locator('#close-settings').click();
  checks.push('profile_and_authenticated_connection');
  await page.locator('#library-tab').click();
  await page.locator('.optional-note summary').click();
  await page.locator('#capture-note').fill('A birthday gift. Avoid bright red.');
  await page.locator('#record-voice').click();
  await page.waitForFunction(()=>document.querySelector('#record-voice')?.textContent==='Stop recording');
  await new Promise(resolve=>setTimeout(resolve,2200));
  await page.locator('#record-voice').click();
  await page.waitForFunction(()=>!document.querySelector('#voice-preview').hidden);
  checks.push('actual_microphone_capture_to_pcm_wav');
  await page.locator('#image-file').setInputFiles([path.join(root,'tests/demo-image.png'),path.join(root,'tests/sample-conversation.png')]);
  await page.waitForFunction(()=>!document.querySelector('.voice-review')?.hidden && document.querySelector('#review-transcript')?.value, null, {timeout:60000});
  await page.locator('#review-transcript').fill('A birthday gift. Please avoid bright red.');
  await page.locator('.correct-transcript').click();
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('Transcript and analysis updated'),null,{timeout:60000});
  assert.match(await page.locator('.insights').innerText(),/Digital wristwatch|digital wristwatch/);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:path.join(directory,'normal-viewport.png')});
  await page.screenshot({path:path.join(directory,'voice-review.png'),fullPage:true});
  checks.push('multiple_image_save_and_transcript_review','transcript_correction_reanalysis');
  await page.locator('.publish-find').click();
  await page.waitForFunction(()=>document.querySelector('.sync-state')?.textContent.includes('Shared library · Saved'),null,{timeout:60000});
  assert.equal(await page.locator('.choices .choice').count(),3);
  await page.locator('.choices .choice').first().click();
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('Your answer is saved'),null,{timeout:60000});
  checks.push('explicit_publication_and_predictive_intent');
  await page.locator('.back-to-library').click();
  await page.locator('#library-query').fill('birthday');
  assert.equal(await page.locator('.library-item').count(),1);
  await page.locator('#library-query').fill('unlikelymissingquery');
  assert.equal(await page.locator('.library-item').count(),0);
  await page.locator('#library-query').fill('');
  checks.push('library_search_analyzed_and_voice_context');
  await page.locator('#explore-tab').click();
  await page.waitForFunction(()=>document.querySelectorAll('.product-card').length>0,null,{timeout:30000});
  await page.locator('.product-card').first().click();
  assert.match(await page.locator('#product-body').innerText(),/Why this\?|Source/);
  await page.screenshot({path:path.join(directory,'explore.png'),fullPage:true});
  await page.locator('#close-product').click();
  checks.push('personalized_explore_and_source_citation');
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('.library-item').length===1,null,{timeout:30000});
  checks.push('panel_reload_recovers_shared_local_mirror');
  await page.locator('#open-settings').click();
  await page.locator('#disconnect').click();
  await page.waitForFunction(()=>document.querySelector('#connection-label')?.textContent==='Connect a shared library');
  await page.locator('#close-settings').click();
  assert.equal(await page.locator('.library-item').count(),0);
  checks.push('disconnect_hides_account_scoped_saves');
  await page.locator('#open-settings').click();
  if (!await page.locator('#backend-token').isVisible()) await page.locator('#settings-dialog details summary').click();
  await page.locator('#backend-token').fill(token);
  await page.locator('#connection-form button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#connection-label')?.textContent.includes('browser-fixture-user'));
  await page.locator('#close-settings').click();
  await page.waitForFunction(()=>document.querySelectorAll('.library-item').length===1);
  await page.locator('.library-item').first().click();
  await page.locator('.delete').click(); await page.locator('.delete').click();
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent.includes('Removed from your device and shared library'));
  assert.equal(await page.locator('.library-item').count(),0);
  checks.push('reconnect_and_delete_media_evidence');
  assert.deepEqual(errors,[],'No uncaught page errors');
  const report={status:'passed',mode:'installed_chromium_fixture',checks,uncaught_errors:errors.length,
    test_host_pregranted:true,external_managed_login:'unit-tested; no personal account used',screenshots_directory:directory};
  await writeFile(path.join(directory,'report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
} catch(error) {
  await page?.screenshot({path:path.join(directory,'failure.png'),fullPage:true}).catch(()=>{});
  await writeFile(path.join(directory,'failure.json'),JSON.stringify({message:error.message,checks,errors},null,2));
  console.error('Browser validation failed; artifacts: '+directory); throw error;
} finally { await context.close(); }
